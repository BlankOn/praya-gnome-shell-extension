#!/usr/bin/env python3
"""Generate contributors.py from the repository's git history.

Usage:
    tools/gen-contributors.py                 # writes ./contributors.py
    PRAYA_CONTRIB_OUT=/tmp/x tools/gen-contributors.py

The output is committed to the repository: the list only changes when a new
person contributes, so a package built from a tarball (which has no .git
directory) still ships a contributor list.

Names and e-mail addresses come from the git author fields, so a .mailmap
(if present) is honoured. Entries are ordered by number of commits
(descending), then by name.
"""
import os
import subprocess
import sys

REPO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.environ.get('PRAYA_CONTRIB_OUT', REPO_DIR)

HEADER = '''\
#!/usr/bin/env python3
"""contributors.py

Generated from git history by tools/gen-contributors.py.

DO NOT EDIT THIS FILE BY HAND. Run ``make contributors`` to regenerate it.

Ordered by number of commits (descending), then by name.
"""

CONTRIBUTORS = [
'''
FOOTER = ']\n'


def collect():
    """Return [((name, email), commit_count), ...] from git history."""
    try:
        result = subprocess.run(
            ['git', 'log', '--all', '--format=%aN%x00%aE'],
            cwd=REPO_DIR, check=True, capture_output=True, text=True)
    except FileNotFoundError:
        sys.exit('gen-contributors: git not found; cannot read history')
    except subprocess.CalledProcessError as exc:
        sys.exit('gen-contributors: git log failed: %s' % exc.stderr.strip())

    counts = {}
    for line in result.stdout.splitlines():
        # Each line is "name\0email"; skip anything malformed.
        if '\x00' not in line:
            continue
        name, email = line.split('\x00', 1)
        name = name.strip()
        email = email.strip()
        if not name:
            continue
        key = (name, email)
        counts[key] = counts.get(key, 0) + 1

    return sorted(counts.items(), key=lambda item: (-item[1], item[0][0].lower()))


def main():
    entries = collect()

    out = [HEADER]
    for (name, email), commits in entries:
        # repr() yields a correctly escaped Python string literal.
        out.append("    {'name': %s, 'email': %s, 'commits': %d},\n"
                   % (repr(name), repr(email), commits))
    out.append(FOOTER)

    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, 'contributors.py')
    with open(path, 'w', encoding='utf-8') as handle:
        handle.write(''.join(out))

    plural = '' if len(entries) == 1 else 's'
    print('==> Wrote %s (%d contributor%s)' % (path, len(entries), plural))


if __name__ == '__main__':
    main()
